"""The runtime shader cache key (layer/shader_cache.cpp) equals tools/shader_identity.py's.

This test computes the keys of a small tree with the Python module and compares them with
tests/shader_cache_key_golden.txt; tests/shader_cache_test.cpp checks the C++ keys against the same
file. Both pass only if the two implementations agree. `--write` regenerates the golden file.
The tree covers: CRLF, blanks around '#', a missing include, '<>' and '""' searches, backslashes,
'..' above the root, an absolute path, an include cycle, a macro include (depends on every file),
a non-ASCII path and a tab (JSON escapes), the SHaRC root, an empty file, defines in the request.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import tools.shader_identity as si  # noqa: E402

GOLDEN = ROOT / "tests" / "shader_cache_key_golden.txt"
TOOL = "bg3rtx-runtime-test-tool"
FILES = {
    "shaders/a.hlsl": '#include "inc/x.hlsli"\r\n#include <missing.h>\n[numthreads(8,1,1)] void main() {}\n',
    "shaders/b.hlsl": '  #  include "common.hlsli"\n#include "..\\common\\w.h"\n[numthreads(8,1,1)] void main() {}\n',
    "shaders/c.hlsl": '// dxc: -enable-16bit-types\n#include <inc/x.hlsli>\n#include "SharcCommon.h"\n'
                      '[numthreads(8,1,1)] void one() {}\n',
    "shaders/d.hlsl": '#define F "x.h"\n#include F\n',
    "shaders/e.hlsl": '#include "ü.hlsli"\n#include "/abs/p.h"\n#include "../../../up.h"\n'
                      '#include " spaced.h "\n#include "tab\t\\"\n#include ""\n#includex "no.h"\n',
    "shaders/ü.hlsli": "// u\n",
    "shaders/inc/x.hlsli": '#include "../../common/h.h"\n#include "x.hlsli"\n',
    "shaders/common.hlsli": "float f;\n",
    "common/h.h": "#pragma once\n#if !defined(__HLSL_VERSION)\n#include <vector>\n#endif\n",
    "common/w.h": "",
    "sharc/SharcCommon.h": '// sharc\n#include "SharcTypes.h"\n',
    "shaders/variants.txt": "d.hlsl?FOO=1\n",
}
REQUESTS = [("a.hlsl", "main", "cs_6_6"), ("a.hlsl?RT_A=1;RT_B=1", "main", "cs_6_6"), ("b.hlsl", "main", "cs_6_0"),
            ("c.hlsl", "one", "cs_6_6"), ("d.hlsl", "main", "cs_6_6"), ("d.hlsl?FOO=1", "main", "cs_6_6"),
            ("e.hlsl", "main", "cs_6_6"), ("inc/x.hlsli", "main", "cs_6_6"), ("missing.hlsl", "main", "cs_6_6")]


def golden_text():
    tree = si.SourceTree.memory(FILES)
    lines = ["# Generated by tests/shader_cache_key_test.py --write: the tree (hex bytes) and the keys",
             f"# tools/shader_identity.py gives it with tool id {TOOL}; tests/shader_cache_test.cpp checks the C++ keys.",
             f"tool {TOOL}"]
    for path, data in FILES.items():
        lines.append(f"file {path} {data.encode().hex()}")
    for request, entry, profile in REQUESTS:
        path = si.SHADERS + "/" + si.split_request(request)[0]
        key = si.entry_key(TOOL, request, entry, tree.closure(path), profile) if path in tree.ids else "-"
        lines.append(f"key {request} {entry} {profile} {key}")
    return "\n".join(lines) + "\n"


def main():
    text = golden_text()
    if "--write" in sys.argv:
        GOLDEN.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", GOLDEN)
        return 0
    if not GOLDEN.exists() or GOLDEN.read_text(encoding="utf-8") != text:
        print("FAIL: tests/shader_cache_key_golden.txt differs from tools/shader_identity.py's keys "
              "(the key logic changed: update layer/shader_cache.cpp to match, then --write)")
        return 1
    # The tree really exercises the special paths.
    closure = dict(si.SourceTree.memory(FILES).closure("shaders/d.hlsl"))
    if "*all*" not in closure:
        print("FAIL: the macro include does not depend on every file")
        return 1
    print(f"shader cache keys: {len(REQUESTS)} requests agree with tools/shader_identity.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
