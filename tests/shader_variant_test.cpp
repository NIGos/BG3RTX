// shaders/variants.txt == every request core/gi.cpp can make (common/shader_variant.h over
// every shaders/gi/*.hlsl and every flag set). `shader_variant_test <root> --write` rewrites it.
#include "../common/shader_variant.h"
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <set>
#include <string>
#include <vector>
using namespace bg3::shader_variant;
static int checks = 0;
#define CHECK(x) do { ++checks; if (!(x)) { std::printf("FAIL line %d: %s\n", __LINE__, #x); std::exit(1); } } while (0)

int main(int argc, char** argv) {
  CHECK(argc >= 2);
  const std::filesystem::path root = argv[1];
  const bool write = argc >= 3 && std::string(argv[2]) == "--write";

  // Fixed spellings: the ordinary path is untouched, defines keep the old wrapper order.
  CHECK(request("gi/rt_shadow.hlsl", 0) == "gi/rt_shadow.hlsl");
  CHECK(request("probe.hlsl", kTileset | kOmm) == "probe.hlsl");
  CHECK(request("gi/gi_ao_apply.hlsl", kCascade | kHairOrigin | kSunCurrent) == "gi/gi_ao_apply.hlsl");
  CHECK(request("gi/rt_origin.hlsl", kHairOrigin) == "gi/rt_origin.hlsl");  // Hair origin needs the scalp
  CHECK(request("gi/rt_shadow.hlsl", kCascade) == "gi/rt_shadow.hlsl?RT_CASCADE_MASKS=1;RT_CASCADE_SUN=1");
  CHECK(request("gi/rt_shadow.hlsl", kSunCurrent | kCascade) ==
        "gi/rt_shadow.hlsl?RT_SUN_CURRENT=1;RT_CASCADE_SUN=1;RT_CASCADE_MASKS=1;RT_CASCADE_TMIN=0.0;RT_CASCADE_TMIN_REL=0.0");
  CHECK(request("gi/gi_trace_rt.hlsl", kTileset | kHairOrigin | kOmm | kScalp | kCascade) ==
        "gi/gi_trace_rt.hlsl?RT_NATIVE_TILESET=1;RT_HAIR_PHYSICAL_ORIGIN=1;RT_OMM_SCENE=1;RT_NATIVE_SCALP=1;"
        "RT_NATIVE_HAIR=1;RT_CASCADE_MASKS=1");
  CHECK(!cascade_entry("gi/rt_sun_resolve.hlsl") && !cascade_entry("gi/rt_hit_two_bounce.hlsl"));
  // rt_hit_material_instanced: only the hit-material consumers, last but cascade; never the ordinary files.
  CHECK(request("gi/rt_hit_material.hlsl", kHitInstanced) == "gi/rt_hit_material.hlsl?RT_HIT_INSTANCED=1");
  CHECK(request("gi/gi_trace_rt_hit_direct.hlsl", kHitInstanced | kCascade | kTileset) ==
        "gi/gi_trace_rt_hit_direct.hlsl?RT_NATIVE_TILESET=1;RT_HIT_INSTANCED=1;RT_CASCADE_MASKS=1");
  CHECK(request("gi/gi_trace_rt.hlsl", kHitInstanced) == "gi/gi_trace_rt.hlsl");
  CHECK(request("gi/rt_shadow.hlsl", kHitInstanced) == "gi/rt_shadow.hlsl");
  // gi_far: the gi_hit_sun files only, last; never the direct-only or ordinary files.
  CHECK(request("gi/gi_trace_rt_hit_sun.hlsl", kGiFar | kCascade) == "gi/gi_trace_rt_hit_sun.hlsl?RT_CASCADE_MASKS=1;RT_GI_FAR=1");
  CHECK(request("gi/gi_trace_rt_sharc_hit_sun_em.hlsl", kGiFar) == "gi/gi_trace_rt_sharc_hit_sun_em.hlsl?RT_GI_FAR=1");
  CHECK(request("gi/gi_trace_rt_hit_direct.hlsl", kGiFar) == "gi/gi_trace_rt_hit_direct.hlsl");
  CHECK(request("gi/gi_trace_rt.hlsl", kGiFar) == "gi/gi_trace_rt.hlsl");
  // rf_hit_gi: the four rf_hit_shade files only, last; never the ordinary D-RF or the GI files.
  CHECK(request("gi/rt_reflections_hit_shade.hlsl", kRfHitGi | kCascade) ==
        "gi/rt_reflections_hit_shade.hlsl?RT_CASCADE_MASKS=1;RF_HIT_GI=1");
  CHECK(request("gi/rt_reflections_sharc_hit_shade_em.hlsl", kRfHitGi | kHitInstanced) ==
        "gi/rt_reflections_sharc_hit_shade_em.hlsl?RT_HIT_INSTANCED=1;RF_HIT_GI=1");
  CHECK(request("gi/rt_reflections.hlsl", kRfHitGi) == "gi/rt_reflections.hlsl");
  CHECK(request("gi/gi_trace_rt_hit_sun.hlsl", kRfHitGi) == "gi/gi_trace_rt_hit_sun.hlsl");

  std::set<std::string> want;
  size_t bases = 0;
  for (const auto& e : std::filesystem::directory_iterator(root / "shaders" / "gi")) {
    if (!e.is_regular_file() || e.path().extension() != ".hlsl") continue;
    const std::string file = "gi/" + e.path().filename().string();
    ++bases;
    const unsigned a = allowed(file.c_str());
    for (unsigned m = 0; m < 1024; ++m)
      if ((m & a) == m && m) {
        const std::string r = request(file.c_str(), m);
        if (r != file) want.insert(r);
      }
  }
  CHECK(bases > 0);
  for (const char* r : kFixedRequests) {   // outside gi/: each names an existing file
    const std::string f(r, std::strchr(r, '?'));
    CHECK(std::filesystem::exists(root / "shaders" / f));
    want.insert(r);
  }
  const std::filesystem::path manifest = root / "shaders" / "variants.txt";
  if (write) {
    std::ofstream o(manifest, std::ios::binary);
    o << "# Generated by tests/shader_variant_test.cpp <root> --write: every GI variant request the core can\n"
         "# make (common/shader_variant.h). tools/compile_shaders.py compiles each one.\n";
    for (const auto& r : want) o << r << "\n";
    std::printf("wrote %zu variants of %zu bases\n", want.size(), bases);
    return 0;
  }
  std::set<std::string> have;
  std::ifstream in(manifest);
  CHECK(in.good());
  for (std::string line; std::getline(in, line);) {
    if (!line.empty() && line.back() == '\r') line.pop_back();
    if (line.empty() || line[0] == '#') continue;
    CHECK(have.insert(line).second);
  }
  for (const auto& r : want)
    if (!have.count(r)) std::printf("missing from shaders/variants.txt: %s\n", r.c_str());
  for (const auto& r : have)
    if (!want.count(r)) std::printf("not requestable (shaders/variants.txt): %s\n", r.c_str());
  CHECK(have == want);
  std::printf("shader_variant_test: %d checks, %zu variants of %zu bases\n", checks, want.size(), bases);
  return 0;
}
