"""Find BG3's camera-occlusion fade ("cut-away") in the depth-prepass fragment shaders.

The fade is not a screen-door dither. A world-space capsule test cuts the pixels of walls,
beams and props near the line from one point to two targets (the camera to the party):

    if (material.flag == 1.0) {                       // per draw, set 1 binding 0 or 1
      n = 2 * noise(uv * 2).x - 1;                    // edge noise in [-1, 1]
      f = min(clamp(max(0.5 * n + distance(P, seg(F.m4, F.m0)), 0) / F.m1, 0, 1),
              clamp(max(0.5 * n + distance(P, seg(F.m4, F.m2)), 0) / F.m3, 0, 1));
    } else f = 1;
    if (alpha * f < cut) discard;                     // cut 1e-4 .. 1.0 per shader

P is the world position (camera-relative input + view UBO m6), F the frame UBO at set 0
binding 6 (vec3 m0; float m1; vec3 m2; float m3; vec3 m4; ...). It is only in the camera's
depth prepass: the lighting keeps the wall (docs/INN_ROTATION_MATCH.md).

Writes shaders/rt/camera_fade_fs.txt, one line per fade-capable shader:

  <fs hash> flag=S.B off=O        the per-draw enable flag (float, == 1.0 enables the cut)

read by layer/alphatest.cpp for the primary-ray check (rt_primary_fade_class). Uses the
decompiled cache of scripts/alpha_table.py (run that first for a new dump).

  py -3 scripts\\camera_fade_table.py [--dump captures\\shaders] [--cache captures\\alpha_cache]
"""
import argparse, collections, concurrent.futures as cf, json, pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import alpha_table  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAPSULE = re.compile(r"spvNMin\(clamp\(spvNMax\(fma\((_\d+), 0\.5, distance\(")
BLOCK = re.compile(r"layout\(set = (\d+), binding = (\d+), std140\) uniform (\w+)\s*\{.*?\}\s*(_\d+);", re.S)


def classify(text, refl):
    """(set, binding, offset) of the fade's enable flag, or None (no camera fade)."""
    m = CAPSULE.search(text)
    if not m: return None
    blocks = {b.group(4): (int(b.group(1)), int(b.group(2)), b.group(3)) for b in BLOCK.finditer(text)}
    # The frame UBO: the capsule reads set 0 binding 6 members m0..m4 only.
    frame = [v for v, b in blocks.items() if b[:2] == (0, 6)]
    if len(frame) != 1: return None
    seg = text[m.start():m.start() + 1200]
    used = set(re.findall(re.escape(frame[0]) + r"\._m(\d+)\b", seg))
    if not used or not used <= {"0", "1", "2", "3", "4"}: return None
    # The enable flag: the last `if (X._mK == 1.0)` before the capsule, on a set 1 UBO.
    gates = list(re.finditer(r"if \((_\d+)\.(_m\d+) == 1\.0\)", text[:m.start()]))
    if not gates: return None
    var, mem = gates[-1].group(1), gates[-1].group(2)
    if var not in blocks or blocks[var][0] != 1: return None
    s, b, tname = blocks[var]
    ubo = [u for u in refl.get("ubos", []) if u["set"] == s and u["binding"] == b]
    if len(ubo) != 1 or ubo[0]["type"] not in refl.get("types", {}): return None
    for member in refl["types"][ubo[0]["type"]]["members"]:
        if member["name"] == mem and member["type"] == "float": return s, b, member["offset"]
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", default=str(ROOT / "captures" / "shaders"))
    ap.add_argument("--cache", default=str(ROOT / "captures" / "alpha_cache"))
    ap.add_argument("--out", default=str(ROOT / "shaders" / "rt" / "camera_fade_fs.txt"))
    a = ap.parse_args()
    cache = pathlib.Path(a.cache)
    tool = alpha_table.spirv_cross()
    spvs = sorted(pathlib.Path(a.dump).glob("*.spv"))
    with cf.ThreadPoolExecutor(16) as ex:
        dec = list(ex.map(lambda p: (p.stem, alpha_table.decompile(tool, p, cache)), spvs))
    rows, why = [], collections.Counter()
    for h, d in dec:
        if not d: continue
        r = classify(*d)
        capsule = bool(CAPSULE.search(d[0]))
        why["fade" if r else "capsule, flag not found" if capsule else "other"] += 1
        if r: rows.append("%s flag=%d.%d off=%d" % (h, *r))
    pathlib.Path(a.out).write_text(
        "# Generated by scripts/camera_fade_table.py from the shader dump: depth-prepass fragment\n"
        "# shaders with BG3's camera-occlusion capsule fade (frame UBO set 0 binding 6), and their\n"
        "# per-draw enable flag (a float UBO member, 1.0 = cut). Diagnostics only: rt_primary_fade_class.\n"
        + "\n".join(rows) + "\n")
    print("%d depth-only discarding fragment shaders: %s -> %s" % (sum(why.values()), dict(why), a.out))
    return 0 if why["capsule, flag not found"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
