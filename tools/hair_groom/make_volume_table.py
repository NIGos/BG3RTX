"""Generate M4.1's diffuse-slab table. Cache each completed cell; print progress per cell.

python -m tools.hair_groom.make_volume_table
The direct-light k table is not a diffuse-incidence calibration. Record both the integrated
dual prediction and its volume correction, and bake S + k_volume M for a cheap shader lookup.
"""
import json
import hashlib
import time
from pathlib import Path

import numpy as np

from tools.low_priority import lower_priority
from . import bsdf, dual


def hlsl(cs, rows):
    return ("// Generated by python -m tools.hair_groom.make_volume_table; see dual.volume_integral.\n"
            "#pragma once\nstatic const float kHvC[9] = {" + ", ".join(map(str, cs)) + "};\n"
            "static const float kHvA[27] = {\n" +
            "\n".join("  " + ", ".join(f"{a:.8f}" for a in row) + "," for row in rows) + "\n};\n")


def main():
    lower_priority()
    root = Path(__file__).resolve().parents[2]
    fingerprint = hashlib.sha256(b"".join((root / p).read_bytes() for p in
        ("tools/hair_groom/bsdf.py", "tools/hair_groom/dual.py", "tools/hair_groom/make_volume_table.py"))).hexdigest()[:16]
    cache = root / f"build/hair_volume_{fingerprint}.json"
    cache.parent.mkdir(exist_ok=True)
    cells = json.loads(cache.read_text()) if cache.exists() else {}
    start = time.monotonic()
    rows = []
    total = len(dual.TABLE_C) * len(dual.TABLE_BETA)
    for i, c in enumerate(dual.TABLE_C):
        row = []
        for j, beta in enumerate(dual.TABLE_BETA):
            key = f"{c}/{beta}"
            if key not in cells:
                s, m = dual.volume_integral((c, c, c), beta)
                # Two independent walks; grey channels share all sampling decisions.
                refs = [float(bsdf.slab_albedo((c,c,c), beta, n=50000, bounces=4000, seed=61+k, diffuse=True, progress=True)[0]) for k in range(2)]
                a = float(np.mean(refs))
                cells[key] = dict(single=float(s[0]), multiple=float(m[0]), k_volume=(a-float(s[0]))/float(m[0]),
                                  albedo=a, references=refs, paths=100000)
                cache.write_text(json.dumps(cells, indent=2) + "\n")
            row.append(cells[key]["albedo"])
            done = i*3+j+1
            elapsed = time.monotonic()-start
            print(f"volume {done}/{total}, c={c} beta={beta}: A={row[-1]:.6f}, "
                  f"{done/max(elapsed,1e-9):.2f} cells/s, elapsed {elapsed:.1f}s "
                  f"ETA {elapsed/done*(total-done):.1f}s, failures 0", flush=True)
        rows.append(row)
    cs = (*dual.TABLE_C, 1.0)
    rows.append([1.0]*3)  # exact conservative nonabsorbing limit
    (root / "tools/hair_groom/volume_calibration.json").write_text(json.dumps(cells, indent=2) + "\n")
    out = root / "tools/hair_groom/volume_table.py"
    out.write_text('"""Generated diffuse-slab reflectances; make_volume_table.py, 100000 paths/cell, seeds 61/62.\n'
                   'White endpoint: exact conservation. Raw calibration: volume_calibration.json.\n"""\n'
                   f"VOLUME_C = {cs!r}\nVOLUME_A = {tuple(tuple(r) for r in rows)!r}\n")
    (root / "shaders/rt/hair_volume_table.hlsli").write_text(hlsl(cs, rows), newline="\n")


if __name__ == "__main__":
    main()
