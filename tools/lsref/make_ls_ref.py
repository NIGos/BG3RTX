"""Freezes the D-LS shader of a git revision into shaders/gi/ls_ref/ (bit-exactness checks).

    py -3 tools/lsref/make_ls_ref.py [rev [out]]     (default HEAD, shaders/gi/ls_ref/ls_ref_body.hlsli)

Writes shaders/gi/ls_ref/ls_ref_body.hlsli: that revision's rt_local_shadows.hlsl main as
    bool ls_ref(uint2 fp, inout float3 o_d, inout float3 o_s)   (false: pixel not written)
together with frozen copies of every function it calls from bg3_lights/bg3_materials/bg3_sun
and the ray-origin/occlusion helpers of rt_common, without resource declarations. It is meant
to be included after the live headers (whose resources it uses); its names get the prefix lsref_.
"""
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
rev = sys.argv[1] if len(sys.argv) > 1 else "HEAD"


def show(path):
    return subprocess.run(["git", "-C", str(root), "show", f"{rev}:{path}"], capture_output=True, text=True,
                          check=True, encoding="utf-8").stdout


def strip(src):
    out = []
    for l in src.splitlines():
        if l.startswith("#pragma once") or l.startswith("#include") or "[[vk::binding" in l:
            continue
        out.append(l)
    return "\n".join(out)


def block(src, start_re):
    """The text of the top-level definition starting at start_re, through its closing brace."""
    m = re.search(start_re, src, re.M)
    if not m:
        raise SystemExit(f"not found: {start_re}")
    i = src.index("{", m.start())
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                end = j + 1
                if src[end:end + 1] == ";":
                    end += 1
                return src[m.start():end]
    raise SystemExit("unbalanced")


rtc = show("shaders/rt/rt_common.hlsli")
rt_parts = [block(rtc, r"^struct RtCone"), block(rtc, r"^bool rt_occluded\("),
            block(rtc, r"^float3 rt_offset_ray\("), block(rtc, r"^float4 rt_origin_at\("),
            block(rtc, r"^float3 rt_ray_origin_o\(")]

main = show("shaders/gi/rt_local_shadows.hlsl")
head, body = main.split("[numthreads(8, 8, 1)]", 1)
head = strip(head)
body = body.replace("void main(uint3 tid : SV_DispatchThreadID) {\n  uint2 fp = tid.xy;\n  if (any(fp >= pc.full)) return;",
                    "bool ls_ref(uint2 fp, inout float3 o_d, inout float3 o_s) {\n  if (any(fp >= pc.full)) return false;", 1)
assert "bool ls_ref(" in body, "main signature changed"
body = re.sub(r"\breturn;", "return false;", body)
body = body.replace("  gDiffuse[fp] = od;\n  gSpecular[fp] = os;\n", "  o_d = od;\n  o_s = os;\n", 1)
assert "o_d = od;" in body, "output writes changed"
body = body.rstrip()
assert body.endswith("}")
body = body[:-1] + "  return true;\n}\n"

lights, mats, sun = (strip(show(f"shaders/rt/{n}")) for n in ("bg3_lights.hlsli", "bg3_materials.hlsli", "bg3_sun.hlsli"))
text = "\n".join([*rt_parts, lights, mats, sun, head, body])
# DXC's namespaces do not hide the global overloads: every name defined here gets a prefix.
names = set(re.findall(r"^(?:static const )?(?:struct|[A-Za-z_][\w<>]*) ([A-Za-z_]\w*)\s*(?:\(|\{|=)", text, re.M))
pattern = re.compile(r"\b(" + "|".join(sorted(names, key=len, reverse=True)) + r")\b")


def rename(src):
    return pattern.sub(r"lsref_\1", src)


short = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", rev], capture_output=True, text=True).stdout.strip()
out = [f"// GENERATED by tools/lsref/make_ls_ref.py from {rev} ({short}). Do not edit.",
       "// Include after the live headers (it uses their resources); every name it defines has the",
       "// prefix lsref_, so the reference pass is lsref_ls_ref(fp, o_d, o_s).",
       "// ---- rt_common.hlsli (ray origin and occlusion) ----", *(rename(x) for x in rt_parts),
       "// ---- bg3_lights.hlsli ----", rename(lights),
       "// ---- bg3_materials.hlsli ----", rename(mats),
       "// ---- bg3_sun.hlsli ----", rename(sun),
       "// ---- rt_local_shadows.hlsl ----", rename(head), rename(body)]
dst = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "shaders" / "gi" / "ls_ref" / "ls_ref_body.hlsli"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {dst}")
